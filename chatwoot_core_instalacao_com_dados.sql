-- Chatwoot Reports | PostgreSQL 14+ / Supabase
-- Executar dentro do banco existente (por exemplo, PostgreSQL do Supabase).
-- Supabase nao permite CREATE DATABASE via SQL Editor: este script cria as tabelas no schema core.
-- Idempotente: pode executar novamente para atualizar os registros das mesmas chaves.
CREATE SCHEMA IF NOT EXISTS core;

BEGIN;

CREATE TABLE IF NOT EXISTS core.agent_report (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  period_start date NOT NULL,
  period_end date NOT NULL,
  agent_name text NOT NULL,
  assigned_conversations integer NOT NULL DEFAULT 0 CHECK (assigned_conversations >= 0),
  avg_first_response interval,
  avg_resolution interval,
  avg_customer_wait interval,
  resolution_count integer NOT NULL DEFAULT 0 CHECK (resolution_count >= 0),
  updated_at timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT agent_report_period_check CHECK (period_end >= period_start),
  CONSTRAINT agent_report_unique UNIQUE (period_start, period_end, agent_name)
);

CREATE TABLE IF NOT EXISTS core.label_report (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  period_start date NOT NULL,
  period_end date NOT NULL,
  label_name text NOT NULL,
  conversation_count integer NOT NULL DEFAULT 0 CHECK (conversation_count >= 0),
  avg_first_response interval,
  avg_resolution interval,
  avg_response interval,
  resolution_count integer NOT NULL DEFAULT 0 CHECK (resolution_count >= 0),
  updated_at timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT label_report_period_check CHECK (period_end >= period_start),
  CONSTRAINT label_report_unique UNIQUE (period_start, period_end, label_name)
);

-- CSV de trafego originalmente usa datas como colunas: normalizado para uma linha por data e hora.
CREATE TABLE IF NOT EXISTS core.conversation_traffic (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  traffic_date date NOT NULL,
  hour_of_day smallint NOT NULL CHECK (hour_of_day BETWEEN 0 AND 23),
  conversation_count integer NOT NULL DEFAULT 0 CHECK (conversation_count >= 0),
  timezone_name text NOT NULL DEFAULT 'America/Sao_Paulo',
  updated_at timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT conversation_traffic_unique UNIQUE (traffic_date, hour_of_day)
);

CREATE TABLE IF NOT EXISTS core.resolution_heatmap (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  resolution_date date NOT NULL,
  hour_of_day smallint NOT NULL CHECK (hour_of_day BETWEEN 0 AND 23),
  resolution_count integer NOT NULL DEFAULT 0 CHECK (resolution_count >= 0),
  updated_at timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT resolution_heatmap_unique UNIQUE (resolution_date, hour_of_day)
);

CREATE INDEX IF NOT EXISTS idx_agent_report_agent ON core.agent_report (agent_name);
CREATE INDEX IF NOT EXISTS idx_label_report_label ON core.label_report (label_name);
CREATE INDEX IF NOT EXISTS idx_traffic_date ON core.conversation_traffic (traffic_date);
CREATE INDEX IF NOT EXISTS idx_resolution_date ON core.resolution_heatmap (resolution_date);

